export type DictKey = keyof typeof STRINGS;

export const t = (
  key: DictKey,
  vars?: Record<string, string | number>,
): string => {
  let text: string = STRINGS[key] ?? String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
};

